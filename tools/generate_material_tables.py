"""Regenerate the frozen 48 kHz material coefficient and shared sine ROMs.

Run with ``pixi run python tools/generate_material_tables.py``. Floating-point
transcendentals belong here, never in the material processing loop. Review ROM
and golden-trace changes together; the checked-in integers define playback.
"""

import math
from pathlib import Path


def write_table(path: Path, name: str, values: list[int], description: str) -> None:
    lines = [f'"""{description}', "", "Generated by tools/generate_material_tables.py; do not edit by hand.", '"""', "", f"{name} = ("]
    for start in range(0, len(values), 8):
        lines.append("    " + ", ".join(map(str, values[start:start + 8])) + ",")
    lines.append(")")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    tables = Path(__file__).resolve().parents[1] / "src/symcrash_python_ap/tables"
    write_table(
        tables / "sine_quarter.py", "SINE_QUARTER_Q15",
        [round(32767 * math.sin(math.pi / 2 * i / 1024)) for i in range(1025)],
        "Quarter-wave sine ROM: 1024 intervals, Q1.15, RNE.",
    )
    write_table(
        tables / "material_svf.py", "SVF_G_Q24",
        [round(math.tan(math.pi * 20 * 1000 ** (i / 1024) / 48000) * (1 << 24))
         for i in range(1025)],
        "SVF g ROM: 20 Hz to 20 kHz logarithmic cutoff, 48 kHz, Q8.24, RNE.",
    )
