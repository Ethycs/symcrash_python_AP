"""Generate the equal-tempered integer-cent pitch ROM; --check verifies it."""
import argparse
from decimal import Decimal, ROUND_HALF_EVEN, localcontext
from pathlib import Path


def generate():
    phase, millihertz = [], []
    with localcontext() as ctx:
        ctx.prec = 80
        ctx.rounding = ROUND_HALF_EVEN
        for pitch_cent in range(12701):
            frequency = Decimal(440) * ctx.power(Decimal(2), Decimal(pitch_cent - 6900) / 1200)
            phase.append(round(frequency * 2**32 / 48000))
            millihertz.append(round(frequency * 1000))
    return {'MIDI_CENT_PHASE_Q32': phase, 'MIDI_CENT_FREQ_MHZ': millihertz}


def render(tables):
    lines = ['"""Frozen equal-tempered pitch ROM (48 kHz, integer cents, profile v1).', '',
        'Generated by tools/generate_pitch_rom.py using Decimal(80), ties-to-even.',
        'Index is absolute MIDI cents 0..12700; A4 is index 6900.',
        'Leaf module: no imports or runtime transcendental calculations.', '"""', '']
    for name, values in tables.items():
        lines.append(name + ' = (')
        for offset in range(0, len(values), 8):
            lines.append('    ' + ', '.join(map(str, values[offset:offset+8])) + ',')
        lines += [')', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / 'src/symcrash_python_ap/pitch_rom.py'
    content = render(generate())
    if args.check:
        if target.read_text(encoding='utf-8') != content:
            raise SystemExit('Pitch ROM differs from its generation recipe')
    else:
        target.write_text(content, encoding='utf-8', newline='\n')
    print('Pitch ROM verified.' if args.check else 'Wrote pitch ROM.')


if __name__ == '__main__':
    main()
