def coeff_to_audio(
    coeffs: np.ndarray,
    headroom_bits: int = 1,
) -> np.ndarray:
    """
    Convert 64 coefficients to 64 audio samples via IDWPT.

    This is the synthesis half of the wavelet transform.
    Since coefficients are generated directly (no FWPT),
    there's no phase-variant combing.

    Args:
        coeffs: 64 leaf coefficients (int16)
        headroom_bits: Headroom scaling (default 1)

    Returns:
        64-sample audio buffer (int16)
    """
    from .lanes import _lifting

    # Scale down for headroom
    scaled = [(int(c) >> headroom_bits) for c in coeffs]

    # Structure as leaves for IDWPT (each leaf has 1 coefficient)
    leaves = [[s] for s in scaled]

    # IDWPT
    from ..wavelet.fast_lifting import idwpt_balanced
    result = idwpt_balanced(leaves, depth=6)

    # Scale back up
    output = np.zeros(64, dtype=np.int16)
    for i, s in enumerate(result[:64]):
        v = s << headroom_bits
        output[i] = max(-32768, min(32767, v))

    return output


