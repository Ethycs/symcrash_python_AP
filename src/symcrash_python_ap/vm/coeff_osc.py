# Pre-allocated buffers
_COEFF_OUTPUT = np.zeros(64, dtype=np.int16)


def coeff_osc_render(
    state: CoeffOscState,
    table: CoeffTable,
    num_samples: int = 64,
) -> np.ndarray:
    """
    Render 64 audio samples using coefficient oscillator.

    Unlike FWPT-based processing, this generates audio directly from
    phase accumulators, ensuring phase continuity across blocks.
    The output is audio samples (not wavelet coefficients).

    For waveform synthesis, uses additive synthesis with harmonics
    defined by the coefficient table.

    Args:
        state: CoeffOscState (modified in place)
        table: CoeffTable defining waveform shape (harmonics)
        num_samples: Block size (must be 64)

    Returns:
        64-element int16 array of audio samples
    """
    global _COEFF_OUTPUT

    # Get current phase increment (with slew)
    phase_inc = state.base_phase_inc
    slew_rate = state.phase_slew_rate
    target = state.target_phase_inc

    # Apply pitch slew per-block
    if slew_rate != 0:
        new_inc = phase_inc + slew_rate * num_samples
        if slew_rate > 0 and new_inc >= target:
            new_inc = target
            state.phase_slew_rate = 0
        elif slew_rate < 0 and new_inc <= target:
            new_inc = target
            state.phase_slew_rate = 0
        state.base_phase_inc = new_inc
        phase_inc = new_inc

    # Generate audio samples using additive synthesis
    # Each "leaf" in the table represents a harmonic
    # - leaf 0: fundamental (stride=1.0)
    # - leaf 1: 2nd harmonic (stride=2.0)
    # - etc.

    # Get main phase accumulator (use node_phases[0] as the carrier phase)
    phase = int(state.node_phases[0])

    for sample in range(num_samples):
        # Accumulate harmonics
        total = 0

        for h in range(min(16, 64)):  # First 16 harmonics
            mag = table.mag_q15[h]
            if mag == 0:
                continue

            stride = table.stride_q16[h]  # Harmonic number in Q16

            # Compute harmonic phase
            # harmonic_phase = phase * (stride / 16384)
            # stride = 16384 * harmonic_number, so:
            # harmonic_phase = phase * harmonic_number
            harmonic_num = stride >> 14  # Convert Q16 to integer
            if harmonic_num == 0:
                harmonic_num = 1

            h_phase = (phase * harmonic_num) & 0xFFFFFFFF

            # Look up sine
            sin_val = _sine_q15(h_phase)

            # Accumulate with magnitude using proper rounding
            total += RSHIFT_RNE(sin_val * mag, 15)

        # Normalize to prevent clipping (divide by sum of mags)
        # Use proper rounding to avoid DC bias
        total = RSHIFT_RNE(total, 1)

        # Saturate
        if total > 32767:
            total = 32767
        elif total < -32768:
            total = -32768

        _COEFF_OUTPUT[sample] = total

        # Advance phase for next sample
        phase = (phase + phase_inc) & 0xFFFFFFFF

    # Update state
    state.node_phases[0] = phase

    return _COEFF_OUTPUT


def coeff_osc_render_with_mix(
    state: CoeffOscState,
    coeff_state: np.ndarray,
    table: CoeffTable,
    base_mix_q15: int,
    num_samples: int = 64,
) -> np.ndarray:
    """
    Render coefficients with CMMM-style base_mix blending.

    The base_mix controls how much of the oscillator's c_base
    is blended into the existing coeff_state (c_state):

        c_cmd = lerp(c_state, c_base, base_mix)
              = c_state + base_mix * (c_base - c_state)

    This replaces the carrier→FWPT→mask→IDWPT path with:
        CoeffOsc → lerp(coeff_state, c_base) → IDWPT

    Args:
        state: CoeffOscState (modified in place)
        coeff_state: Current coefficient state (64 x int16)
        table: CoeffTable defining waveform shape
        base_mix_q15: Blend factor (0 = pure state, 32767 = pure osc)
        num_samples: Block size (64)

    Returns:
        Blended coefficients for IDWPT
    """
    # Generate base coefficients from oscillator
    c_base = coeff_osc_render(state, table, num_samples)

    # If base_mix is 0, return current state (no oscillator contribution)
    if base_mix_q15 == 0:
        return coeff_state[:64].astype(np.int16)

    # If base_mix is full, return pure oscillator
    if base_mix_q15 >= Q15_ONE:
        return c_base

    # Blend: c_cmd = c_state + base_mix * (c_base - c_state)
    # This is the orthogonal residual form
    c_state_64 = coeff_state[:64].astype(np.int32)
    c_base_32 = c_base.astype(np.int32)

    residual = c_base_32 - c_state_64
    blended = c_state_64 + ((residual * base_mix_q15) >> 15)

    # Saturate
    return np.clip(blended, -32768, 32767).astype(np.int16)


