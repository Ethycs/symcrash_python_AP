"""
Coefficient Oscillator (WSE-STD-ARCH-CCS v0)
============================================

Generates wavelet coefficients directly from phase accumulators and tables,
bypassing FWPT entirely in the voice path. This eliminates phase-variant
combing artifacts that occur when carrier audio is transformed per-block.

Mode A: Table-Orbit Oscillator
------------------------------
Each leaf coefficient is generated by:
    phi_i += phase_inc * stride_i
    coeff[i] = mag_i * sin(phi_i)

Where:
- phi_i: Per-leaf phase accumulator (32-bit)
- phase_inc: Base phase increment (from MIDI note)
- stride_i: Per-leaf frequency multiplier (from table)
- mag_i: Per-leaf magnitude (from table)

Leaf-Shared Phases (Optimization)
---------------------------------
Instead of 64 independent phases, use:
- phi_leaf[32]: One phase per tree node (nodes 0-31)
- phi_sub[8]: Sub-leaf phases for fine detail

This reduces state from 64 phases to 40 while maintaining quality.
"""

from dataclasses import dataclass, field
from typing import List, Optional, Tuple
import numpy as np

from ..wavelet.sine_core import sine_q15 as _sine_q15, cosine_q15 as _cosine_q15
from ..fixed import RSHIFT_RNE

# Import 2D coefficient tables for true coefficient-domain carrier
# Use the FAST tables (FWPT-based, lazy generation) instead of slow iterative solver
from .coeff_tables_fast import FastCoeffTable2D as CoeffTable2D, get_fast_coeff_table as get_coeff_table_2d

# Q15 constants
Q15_ONE = 32767
Q15_HALF = 16384


# =============================================================================
# COEFFICIENT TABLES
# =============================================================================

@dataclass
class CoeffTable:
    """
    Coefficient oscillator table defining waveform shape.

    Each entry describes how one leaf coefficient behaves:
    - mag_q15: Magnitude in Q15 (0 = silent, 32767 = full)
    - stride_q16: Frequency stride in Q16 (16384 = 1x fundamental)

    The stride determines the harmonic relationship:
    - stride = 16384 (1.0): Fundamental
    - stride = 32768 (2.0): 2nd harmonic
    - stride = 49152 (3.0): 3rd harmonic
    """
    table_id: int = 0
    name: str = "default"
    mag_q15: List[int] = field(default_factory=lambda: [Q15_ONE] + [0] * 63)
    stride_q16: List[int] = field(default_factory=lambda: [16384] * 64)
    norm_rms_q15: int = Q15_ONE  # RMS normalization factor


def _build_sine_table() -> CoeffTable:
    """Build pure sine wave table (energy in first leaf only)."""
    mag = [Q15_ONE] + [0] * 63
    stride = [16384] * 64  # All at fundamental
    return CoeffTable(table_id=0, name="sine", mag_q15=mag, stride_q16=stride)


def _build_saw_table() -> CoeffTable:
    """
    Build sawtooth wave table.

    Sawtooth spectrum: 1/n for harmonic n
    First 16 harmonics mapped to first 16 leaves (2 leaves per node for 8 nodes).
    """
    mag = [0] * 64
    stride = [16384] * 64

    # First 16 harmonics with 1/n amplitude scaling
    for h in range(1, 17):
        leaf_idx = h - 1
        # 1/n scaling: h=1 gets full, h=16 gets 1/16
        mag[leaf_idx] = Q15_ONE // h
        stride[leaf_idx] = 16384 * h  # Harmonic h

    # Normalize to prevent clipping
    total = sum(mag)
    if total > 0:
        scale = (Q15_ONE << 15) // total
        mag = [(m * scale) >> 15 for m in mag]

    return CoeffTable(table_id=1, name="saw", mag_q15=mag, stride_q16=stride)


def _build_square_table() -> CoeffTable:
    """
    Build square wave table.

    Square spectrum: 1/n for odd harmonics only
    """
    mag = [0] * 64
    stride = [16384] * 64

    # Odd harmonics only: 1, 3, 5, 7, 9, 11, 13, 15
    for i, h in enumerate([1, 3, 5, 7, 9, 11, 13, 15]):
        mag[i] = Q15_ONE // h
        stride[i] = 16384 * h

    # Normalize
    total = sum(mag)
    if total > 0:
        scale = (Q15_ONE << 15) // total
        mag = [(m * scale) >> 15 for m in mag]

    return CoeffTable(table_id=2, name="square", mag_q15=mag, stride_q16=stride)


def _build_triangle_table() -> CoeffTable:
    """
    Build triangle wave table.

    Triangle spectrum: 1/n^2 for odd harmonics only, alternating sign
    """
    mag = [0] * 64
    stride = [16384] * 64

    # Odd harmonics with 1/n^2 scaling
    for i, h in enumerate([1, 3, 5, 7, 9, 11, 13, 15]):
        mag[i] = Q15_ONE // (h * h)
        stride[i] = 16384 * h

    # Normalize
    total = sum(mag)
    if total > 0:
        scale = (Q15_ONE << 15) // total
        mag = [(m * scale) >> 15 for m in mag]

    return CoeffTable(table_id=3, name="triangle", mag_q15=mag, stride_q16=stride)


# Pre-built tables
COEFF_TABLES = {
    0: _build_sine_table(),
    1: _build_saw_table(),
    2: _build_square_table(),
    3: _build_triangle_table(),
}


def get_coeff_table(table_id: int) -> CoeffTable:
    """Get coefficient table by ID."""
    return COEFF_TABLES.get(table_id, COEFF_TABLES[0])


# =============================================================================
# COEFFICIENT OSCILLATOR STATE
# =============================================================================

@dataclass
class CoeffOscState:
    """
    Coefficient oscillator state.

    Uses leaf-shared phase optimization:
    - 32 node phases (one per WPT node)
    - 8 sub-leaf phases (for fine detail within nodes)

    Total: 40 x 4 bytes = 160 bytes per voice
    """
    # Node phases (32 x 32-bit)
    node_phases: np.ndarray = field(
        default_factory=lambda: np.zeros(32, dtype=np.uint32)
    )

    # Sub-leaf phases for fine detail (8 x 32-bit)
    sub_phases: np.ndarray = field(
        default_factory=lambda: np.zeros(8, dtype=np.uint32)
    )

    # Current table ID
    table_id: int = 0

    # Base phase increment (from MIDI note)
    base_phase_inc: int = 0

    # Target phase increment (for slew)
    target_phase_inc: int = 0

    # Phase slew rate per sample
    phase_slew_rate: int = 0

    def reset(self, phase_inc: int = 0, table_id: int = 0) -> None:
        """Reset oscillator state for new note."""
        self.node_phases.fill(0)
        self.sub_phases.fill(0)
        self.table_id = table_id
        self.base_phase_inc = phase_inc
        self.target_phase_inc = phase_inc
        self.phase_slew_rate = 0

    def set_pitch(self, phase_inc: int, slew_blocks: int = 8) -> None:
        """Set target pitch with optional slew."""
        if slew_blocks <= 0:
            # Immediate
            self.base_phase_inc = phase_inc
            self.target_phase_inc = phase_inc
            self.phase_slew_rate = 0
        else:
            # Slew over N blocks (64 samples each)
            self.target_phase_inc = phase_inc
            diff = phase_inc - self.base_phase_inc
            # Divide by (blocks * 64 samples)
            self.phase_slew_rate = diff // (slew_blocks * 64)


