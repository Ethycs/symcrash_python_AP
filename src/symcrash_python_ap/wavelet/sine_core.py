# FREQUENCY CONVERSION
# =============================================================================

def freq_to_phase_inc(freq_hz: float, sample_rate: int = 48000) -> int:
    """
    Convert frequency in Hz to phase increment.

    phase_inc = freq * 2^32 / sample_rate

    Args:
        freq_hz: Frequency in Hz
        sample_rate: Sample rate in Hz

    Returns:
        32-bit phase increment
    """
    return int((freq_hz * (1 << PHASE_BITS)) / sample_rate) & PHASE_MASK


def midi_to_freq(note: int, cents: int = 0) -> float:
    """Convert MIDI note number to frequency."""
    return 440.0 * (2.0 ** ((note - 69 + cents / 100.0) / 12.0))


def midi_to_phase_inc(note: int, cents: int = 0, sample_rate: int = 48000) -> int:
    """Convert MIDI note directly to phase increment."""
    freq = midi_to_freq(note, cents)
    return freq_to_phase_inc(freq, sample_rate)


