# OSCILLATOR VOICE STATE
# =============================================================================

@dataclass
class OscillatorState:
    """
    Per-voice oscillator state.

    Separates state from the pure SineCore primitive.
    """
    phase: int = 0                  # Current phase (32-bit)
    phase_inc: int = 0              # Phase increment per sample
    target_phase_inc: int = 0       # Target for pitch slew
    slew_rate: int = 0              # Per-sample slew amount (0 = no slew)

    def reset(self, phase: int = 0) -> None:
        """Hard reset phase (note-on with phase sync)."""
        self.phase = phase & PHASE_MASK

    def set_frequency(self, freq_hz: float, sample_rate: int = 48000) -> None:
        """Set frequency immediately (no slew)."""
        self.phase_inc = freq_to_phase_inc(freq_hz, sample_rate)
        self.target_phase_inc = self.phase_inc
        self.slew_rate = 0

    def set_frequency_slew(
        self,
        freq_hz: float,
        slew_time_ms: float,
        sample_rate: int = 48000,
    ) -> None:
        """Set target frequency with portamento slew."""
        self.target_phase_inc = freq_to_phase_inc(freq_hz, sample_rate)

        if slew_time_ms <= 0:
            self.phase_inc = self.target_phase_inc
            self.slew_rate = 0
            return

        # Calculate slew rate (phase_inc change per sample)
        slew_samples = int(slew_time_ms * sample_rate / 1000)
        if slew_samples <= 0:
            slew_samples = 1

        delta = self.target_phase_inc - self.phase_inc
        self.slew_rate = delta // slew_samples
        if self.slew_rate == 0 and delta != 0:
            self.slew_rate = 1 if delta > 0 else -1

    def advance(self) -> int:
        """
        Advance phase by one sample, applying pitch slew.

        Returns:
            Current phase (before advance) for sample generation
        """
        current_phase = self.phase

        # Apply pitch slew
        if self.slew_rate != 0:
            if self.slew_rate > 0:
                self.phase_inc = min(self.target_phase_inc,
                                     self.phase_inc + self.slew_rate)
            else:
                self.phase_inc = max(self.target_phase_inc,
                                     self.phase_inc + self.slew_rate)

            if self.phase_inc == self.target_phase_inc:
                self.slew_rate = 0

        # Advance phase
        self.phase = (self.phase + self.phase_inc) & PHASE_MASK

        return current_phase


