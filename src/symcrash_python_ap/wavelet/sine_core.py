def verify_accuracy(num_samples: int = 10000) -> Tuple[float, float, float]:
    """
    Verify sine accuracy against math.sin.

    Returns:
        (max_error_lsb, rms_error_lsb, thd_percent)
    """
    import numpy as np

    errors = []
    for i in range(num_samples):
        phase = int((i / num_samples) * (1 << PHASE_BITS))
        theta = 2 * math.pi * i / num_samples

        actual = sine_q15(phase)
        expected = Q_SCALE * math.sin(theta)
        error = abs(actual - expected)
        errors.append(error)

    max_error = max(errors)
    rms_error = math.sqrt(sum(e * e for e in errors) / len(errors))

    # Compute THD via FFT
    samples = [sine_q15(int((i / 4096) * (1 << PHASE_BITS))) for i in range(4096)]
    fft = np.fft.rfft(samples)
    mags = np.abs(fft)

    # Fundamental is at index 1 for single-cycle
    fund = mags[1]
    harmonic_sum_sq = sum(mags[h] ** 2 for h in range(2, 10) if h < len(mags))
    thd = 100 * math.sqrt(harmonic_sum_sq) / fund if fund > 0 else 0

    return max_error, rms_error, thd


def self_test() -> bool:
    """
    Run self-test to verify SineCore correctness.

    Returns:
        True if all tests pass
    """
    print("SineCore Self-Test")
    print("=" * 40)

    # Test 1: Boundary values
    print("\n1. Boundary values:")
    tests = [
        (0x00000000, "sin(0°)", 0),
        (0x40000000, "sin(90°)", Q_SCALE),
        (0x80000000, "sin(180°)", 0),
        (0xC0000000, "sin(270°)", -Q_SCALE),
    ]
    passed = True
    for phase, name, expected in tests:
        actual = sine_q15(phase)
        # Allow ±1 LSB for quantization
        ok = abs(actual - expected) <= 1
        print(f"   {name}: {actual} (expected {expected}) {'OK' if ok else 'FAIL'}")
        passed = passed and ok

    # Test 2: Cosine = sin + 90°
    print("\n2. Cosine identity:")
    cos_tests = [
        (0x00000000, "cos(0°)", Q_SCALE),
        (0x40000000, "cos(90°)", 0),
        (0x80000000, "cos(180°)", -Q_SCALE),
        (0xC0000000, "cos(270°)", 0),
    ]
    for phase, name, expected in cos_tests:
        actual = cosine_q15(phase)
        ok = abs(actual - expected) <= 1
        print(f"   {name}: {actual} (expected {expected}) {'OK' if ok else 'FAIL'}")
        passed = passed and ok

    # Test 3: Accuracy
    print("\n3. Accuracy (10000 samples):")
    max_err, rms_err, thd = verify_accuracy()
    print(f"   Max error: {max_err:.2f} LSB")
    print(f"   RMS error: {rms_err:.2f} LSB")
    print(f"   THD: {thd:.4f}%")

    accuracy_ok = max_err < 2.0 and thd < 0.1
    print(f"   Accuracy: {'OK' if accuracy_ok else 'FAIL'}")
    passed = passed and accuracy_ok

    # Test 4: Monotonicity in first quadrant
    print("\n4. Monotonicity (Q1):")
    prev = -1
    mono_ok = True
    for i in range(1024):
        phase = int((i / 4096) * (1 << PHASE_BITS))  # 0 to 90°
        val = sine_q15(phase)
        if val < prev:
            print(f"   Non-monotonic at {i}: {prev} -> {val}")
            mono_ok = False
            break
        prev = val
    print(f"   Monotonicity: {'OK' if mono_ok else 'FAIL'}")
    passed = passed and mono_ok

    print("\n" + "=" * 40)
    print(f"RESULT: {'PASS' if passed else 'FAIL'}")

    return passed


