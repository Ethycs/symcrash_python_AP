def render_sine_block(
    state: OscillatorState,
    block_size: int = 64,
) -> list:
    """
    Render a block of sine samples.

    Args:
        state: Oscillator state (modified in place)
        block_size: Number of samples

    Returns:
        List of Q15 samples
    """
    samples = []
    for _ in range(block_size):
        phase = state.advance()
        samples.append(sine_q15(phase))
    return samples


def render_sincos_block(
    state: OscillatorState,
    block_size: int = 64,
) -> Tuple[list, list]:
    """
    Render a block of sine and cosine samples.

    Args:
        state: Oscillator state (modified in place)
        block_size: Number of samples

    Returns:
        (sin_samples, cos_samples) tuple
    """
    sin_samples = []
    cos_samples = []
    for _ in range(block_size):
        phase = state.advance()
        sin_samples.append(sine_q15(phase))
        cos_samples.append(cosine_q15(phase))
    return sin_samples, cos_samples


