"""
Sine LUT Generator
==================

Offline tool to generate quarter-wave sine lookup tables for FPGA and Python.

Supports:
- Configurable table sizes (1024, 2048, 4096 entries)
- Q15 or Q17 output format
- Hex/mem file export for FPGA
- Python list export for software reference
- Built-in self-test against math.sin

The quarter-wave symmetry reduces table size by 4x:
- sin(θ) for θ ∈ [0, π/2] stored directly
- sin(θ) for θ ∈ [π/2, π] = sin(π - θ) (mirror)
- sin(θ) for θ ∈ [π, 2π] = -sin(θ - π) (negate)
"""

import math
from pathlib import Path
from typing import List, Tuple, Optional
import argparse


# =============================================================================
# LUT GENERATION
# =============================================================================

def generate_quarter_wave_lut(
    table_size: int = 1024,
    q_bits: int = 15,
) -> List[int]:
    """
    Generate quarter-wave sine lookup table.

    Args:
        table_size: Number of entries (1024 or 2048 recommended)
        q_bits: Q format bits (15 for Q15, 17 for Q17)

    Returns:
        List of signed integers representing sin(θ) for θ ∈ [0, π/2]
    """
    q_scale = (1 << q_bits) - 1  # e.g., 32767 for Q15

    table = []
    for i in range(table_size + 1):  # +1 for interpolation boundary
        # θ = (π/2) * (i / table_size)
        theta = (math.pi / 2) * (i / table_size)
        value = int(round(q_scale * math.sin(theta)))
        # Clamp to q_scale (should only hit at i=table_size)
        value = min(value, q_scale)
        table.append(value)

    return table


def verify_lut(
    table: List[int],
    table_size: int,
    q_bits: int = 15,
) -> Tuple[float, float, bool]:
    """
    Verify LUT accuracy against math.sin.

    Args:
        table: The generated LUT
        table_size: Number of entries (excluding boundary)
        q_bits: Q format bits

    Returns:
        (max_error_lsb, rms_error_lsb, passed)
    """
    q_scale = (1 << q_bits) - 1

    errors = []
    for i in range(table_size + 1):
        theta = (math.pi / 2) * (i / table_size)
        expected = q_scale * math.sin(theta)
        actual = table[i]
        error = abs(actual - expected)
        errors.append(error)

    max_error = max(errors)
    rms_error = math.sqrt(sum(e * e for e in errors) / len(errors))

    # Pass if max error < 1 LSB (quantization only)
    passed = max_error < 1.5

    return max_error, rms_error, passed


def verify_symmetry(table: List[int], table_size: int) -> Tuple[bool, str]:
    """
    Verify quarter-wave symmetry properties.

    For a proper quarter-wave table:
    - table[0] should be 0 (sin(0) = 0)
    - table[table_size] should be max (sin(π/2) = 1)
    - table[i] should be increasing for i in [0, table_size]

    Returns:
        (passed, message)
    """
    issues = []

    # Check endpoints
    if table[0] != 0:
        issues.append(f"table[0] = {table[0]}, expected 0")

    # Check monotonicity
    for i in range(1, table_size + 1):
        if table[i] < table[i - 1]:
            issues.append(f"Non-monotonic at {i}: {table[i-1]} -> {table[i]}")
            break

    if issues:
        return False, "; ".join(issues)
    return True, "Symmetry OK"


# =============================================================================
# EXPORT FUNCTIONS
# =============================================================================

def export_python(
    table: List[int],
    table_size: int,
    q_bits: int,
    output_path: Path,
) -> None:
    """Export LUT as Python module."""
    with open(output_path, "w") as f:
        f.write(f'"""\n')
        f.write(f"Quarter-Wave Sine LUT\n")
        f.write(f"=====================\n")
        f.write(f"\n")
        f.write(f"Auto-generated by sine_lut_gen.py\n")
        f.write(f"Table size: {table_size} entries\n")
        f.write(f"Format: Q{q_bits} signed integer\n")
        f.write(f'"""\n\n')

        f.write(f"TABLE_SIZE = {table_size}\n")
        f.write(f"Q_BITS = {q_bits}\n")
        f.write(f"Q_SCALE = {(1 << q_bits) - 1}\n\n")

        f.write("SINE_LUT_Q15 = [\n")
        for i in range(0, len(table), 8):
            chunk = table[i:i + 8]
            f.write("    " + ", ".join(f"{v:5d}" for v in chunk) + ",\n")
        f.write("]\n")


def export_hex(
    table: List[int],
    output_path: Path,
    width_bits: int = 16,
) -> None:
    """Export LUT as hex file for FPGA ROM initialization."""
    hex_width = (width_bits + 3) // 4  # Hex digits needed

    with open(output_path, "w") as f:
        for value in table:
            # Handle signed values
            if value < 0:
                value = (1 << width_bits) + value
            f.write(f"{value:0{hex_width}X}\n")


def export_mem(
    table: List[int],
    output_path: Path,
    width_bits: int = 16,
) -> None:
    """Export LUT as .mem file (Verilog $readmemh format)."""
    hex_width = (width_bits + 3) // 4

    with open(output_path, "w") as f:
        f.write("// Quarter-wave sine LUT\n")
        f.write(f"// {len(table)} entries, {width_bits}-bit signed\n")
        f.write("// Format: $readmemh compatible\n\n")

        for i, value in enumerate(table):
            if value < 0:
                value = (1 << width_bits) + value
            if i % 8 == 0:
                f.write(f"// {i:04d}: ")
            f.write(f"{value:0{hex_width}X} ")
            if i % 8 == 7:
                f.write("\n")
        f.write("\n")


# =============================================================================
# MAIN CLI
# =============================================================================

def main():
    parser = argparse.ArgumentParser(
        description="Generate quarter-wave sine LUT for FPGA and Python"
    )
    parser.add_argument(
        "--size", type=int, default=1024,
        choices=[256, 512, 1024, 2048, 4096],
        help="Table size (default: 1024)"
    )
    parser.add_argument(
        "--q-bits", type=int, default=15,
        choices=[15, 17],
        help="Q format bits (default: 15)"
    )
    parser.add_argument(
        "--output-dir", type=Path, default=Path(__file__).parent,
        help="Output directory"
    )
    parser.add_argument(
        "--name", type=str, default="sine_lut",
        help="Base name for output files"
    )
    parser.add_argument(
        "--formats", type=str, default="py,hex,mem",
        help="Output formats (comma-separated: py,hex,mem)"
    )

    args = parser.parse_args()

    print("=" * 60)
    print("SINE LUT GENERATOR")
    print("=" * 60)
    print(f"\nTable size: {args.size}")
    print(f"Q format: Q{args.q_bits}")
    print(f"Output dir: {args.output_dir}")

    # Generate
    print("\nGenerating quarter-wave LUT...")
    table = generate_quarter_wave_lut(args.size, args.q_bits)
    print(f"  Generated {len(table)} entries")

    # Verify
    print("\nVerifying accuracy...")
    max_err, rms_err, passed = verify_lut(table, args.size, args.q_bits)
    print(f"  Max error: {max_err:.4f} LSB")
    print(f"  RMS error: {rms_err:.4f} LSB")
    print(f"  Accuracy: {'PASS' if passed else 'FAIL'}")

    print("\nVerifying symmetry...")
    sym_passed, sym_msg = verify_symmetry(table, args.size)
    print(f"  {sym_msg}")

    # Export
    formats = [f.strip().lower() for f in args.formats.split(",")]
    args.output_dir.mkdir(parents=True, exist_ok=True)

    if "py" in formats:
        py_path = args.output_dir / f"{args.name}.py"
        export_python(table, args.size, args.q_bits, py_path)
        print(f"\nExported: {py_path}")

    if "hex" in formats:
        hex_path = args.output_dir / f"{args.name}.hex"
        export_hex(table, hex_path)
        print(f"Exported: {hex_path}")

    if "mem" in formats:
        mem_path = args.output_dir / f"{args.name}.mem"
        export_mem(table, mem_path)
        print(f"Exported: {mem_path}")

    print("\n" + "=" * 60)
    print("DONE")
    print("=" * 60)

    return 0 if passed and sym_passed else 1


if __name__ == "__main__":
    exit(main())
